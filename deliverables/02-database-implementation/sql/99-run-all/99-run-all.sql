    IN p_location_id uuid,
    IN p_product_id uuid,
    IN p_qty integer,
    IN p_user_id integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_year integer := EXTRACT(YEAR FROM now())::int;
    v_month integer := EXTRACT(MONTH FROM now())::int;
    v_num integer;
    v_docno text;
    v_after integer;
